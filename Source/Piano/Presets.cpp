String Presets::VoiceTitle(String voice)
{
	if (voice == "")
	{
		return "";
	}

	bool isPath = voice.startsWith("PRESET:/VOICE");
	int num = isPath ? -1 : voice.getIntValue();
	for (Voice& vc : voices)
	{
		if ((isPath && vc.path == voice) ||
			(!isPath && vc.num == num))
		{
			return vc.title;
		}
	}

	if (!isPath)
	{
		if (const ExtraVoice* extra = FindExtraVoice(num))
		{
			return extra->title; // an XG, GM2 or GS voice, or a Mega Voice: its own name
		}

		std::map<int,int>::iterator it = voiceMap.find(num);
		if (it != voiceMap.end())
		{
			num = it->second;
			if (num == -1)
			{
				// known num voice but without proper mapping, format as "MSB-LSB-PC"
				return String(num >> 16 & 0x7f) + "-" + String(num >> 8 & 0x7f) + "-" + String(num & 0x7f);
			}
			for (Voice& vc : voices)
			{
				if (vc.num == num)
				{
					return vc.category2;
				}
			}
		}

		if ((num >> 16 & 0x7f) == 119)
		{
			// a GS voice that is not in the list (in GS mode the piano reports any voice
			// as 119 / bank MSB / program): the General MIDI name of the program
			return GmVoiceNames()[num & 0x7f];
		}

		// unknown num voice, format as "MSB LSB PC"
		return String(num >> 16 & 0x7f) + " " + String(num >> 8 & 0x7f) + " " + String(num & 0x7f);
	}

	// unknown path
	return voice;
}

Voice* Presets::FindVoice(String voice)
{
	if (voice == "")
	{
		return nullptr;
	}

	bool isPath = voice.startsWith("PRESET:/VOICE");
	int num = isPath ? -1 : voice.getIntValue();
	for (Voice& vc : voices)
	{
		if ((isPath && vc.path == voice) ||
			(!isPath && vc.num == num))
		{
			return &vc;
		}
	}

	if (!isPath)
	{
		std::map<int,int>::iterator it = voiceMap.find(num);
		if (it != voiceMap.end())
		{
			num = it->second;
			if (num == -1)
			{
				// known num voice but without proper mapping
				return nullptr;
			}
			for (Voice& vc : voices)
			{
				if (vc.num == num)
				{
					return &vc;
				}
			}
		}

		// unknown num voice
		return nullptr;
	}

	// unknown path
	return nullptr;
}

String Presets::ReverbEffectTitle(int num)
{
	for (ReverbEffect& re : reverbEffects)
	{
		if (re.num == num)
		{
			return re.title;
		}
	}

	return "Unknown Effect";
}


