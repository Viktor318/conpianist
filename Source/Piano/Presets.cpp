const ExtraVoice* Presets::FindExtraVoice(int num)
{
	static std::map<int, const ExtraVoice*> byNum;
	if (byNum.empty())
	{
		for (const ExtraVoice& voice : ExtraVoices())
		{
			byNum[voice.num] = &voice;
		}
	}
	const auto it = byNum.find(num);
	return it != byNum.end() ? it->second : nullptr;
}

String Presets::VoiceName(int num)
{
	for (Voice& vc : voices)
	{
		if (vc.num == num)
		{
			return vc.title;
		}
	}
	if (const ExtraVoice* extra = FindExtraVoice(num))
	{
		return extra->title;
	}
	Voice* nearest = FindVoice(String(num));
	return nearest ? nearest->category2 : String();
}

